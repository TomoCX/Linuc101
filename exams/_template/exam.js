/* =======================================================================
   試験の定義：__TITLE__
   -----------------------------------------------------------------------
   new-exam.ps1 がひな形（exams/_template）から作ったファイル。
   ここで決めた主題の番号で、このフォルダの問題・ノート・単語帳がこの試験の分と判断される。

   決めること
     id         : 試験ID（フォルダ名と同じ。変えない）
     title      : 選択画面・ホーム・Claudeにコピーに出る名前
     categories : 出題範囲の主題 { 番号: 名前 }。番号は「数字.数字」の形で、
                  ほかの試験と重ならないこと（公式の主題番号を使うのがおすすめ）
     intro      : ノートで「主題」の付かない大見出し（冒頭・直前チェック）に使う番号。
                  ほかの試験の主題番号と重ならなければ何でもよい（ふつうは試験ID）
     searchHint : ノートの検索欄に出す例（任意）
   ======================================================================= */

registerExam({
  id: "__ID__",
  title: "__TITLE__",
  categories: {
    "__CAT__": "（主題の名前）"
  },
  intro: "__ID__",
  searchHint: ""
});
